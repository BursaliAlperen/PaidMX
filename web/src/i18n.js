let currentLang = "tr";
try {
  const saved = localStorage.getItem("paidmx_lang");
  if (saved === "en" || saved === "tr") currentLang = saved;
} catch (_) {}

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (lang !== "tr" && lang !== "en") return;
  currentLang = lang;
  try { localStorage.setItem("paidmx_lang", lang); } catch (_) {}
}

export function t(key) {
  const table = STRINGS[currentLang] || STRINGS.tr;
  return table[key] != null ? table[key] : (STRINGS.tr[key] != null ? STRINGS.tr[key] : key);
}
